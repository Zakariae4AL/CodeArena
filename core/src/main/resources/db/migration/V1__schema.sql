-- CodeArena schema. Written to run on PostgreSQL (production) and H2 in PostgreSQL mode (tests).
-- Modules never share tables and only refer to each other's rows by id (no cross-module foreign keys),
-- so any module could later move to its own database.

-- identity
create table users (
    id            bigint generated by default as identity primary key,
    username      varchar(20)  not null,
    email         varchar(255) not null,
    password_hash varchar(100) not null,
    role          varchar(10)  not null,
    created_at    timestamp(6) with time zone not null,
    constraint uk_users_username unique (username),
    constraint uk_users_email unique (email)
);

-- problems
create table problems (
    id              bigint generated by default as identity primary key,
    slug            varchar(60)  not null,
    title           varchar(120) not null,
    statement       varchar(100000) not null,
    difficulty      varchar(10)  not null,
    time_limit_ms   integer      not null,
    memory_limit_mb integer      not null,
    published       boolean      not null,
    created_at      timestamp(6) with time zone not null,
    constraint uk_problems_slug unique (slug)
);

create table test_cases (
    id         bigint generated by default as identity primary key,
    problem_id bigint  not null references problems (id) on delete cascade,
    position   integer not null,
    input      varchar(2000000) not null,
    expected   varchar(2000000) not null,
    sample     boolean not null
);
create index ix_test_cases_problem on test_cases (problem_id, position);

-- contests
create table contests (
    id          bigint generated by default as identity primary key,
    slug        varchar(60)  not null,
    title       varchar(120) not null,
    description varchar(20000) not null,
    starts_at   timestamp(6) with time zone not null,
    ends_at     timestamp(6) with time zone not null,
    created_at  timestamp(6) with time zone not null,
    constraint uk_contests_slug unique (slug)
);

create table contest_problems (
    contest_id bigint      not null references contests (id) on delete cascade,
    problem_id bigint      not null,
    label      varchar(2)  not null,
    position   integer     not null,
    primary key (contest_id, problem_id),
    constraint uk_contest_problems_label unique (contest_id, label)
);

-- submissions
create table submissions (
    id             uuid         primary key,
    user_id        bigint       not null,
    problem_id     bigint       not null,
    contest_id     bigint,
    language       varchar(20)  not null,
    mode           varchar(10)  not null,
    source         varchar(70000) not null,
    status         varchar(10)  not null,
    verdict        varchar(30),
    passed         integer      not null,
    total          integer      not null,
    time_ms        bigint       not null,
    memory_kb      bigint       not null,
    compile_output varchar(20000),
    message        varchar(500),
    test_results   varchar(200000),
    created_at     timestamp(6) with time zone not null,
    judged_at      timestamp(6) with time zone
);
create index ix_submissions_user on submissions (user_id, created_at);
create index ix_submissions_problem on submissions (problem_id, user_id);

-- leaderboard (a projection built from SubmissionJudged events)
create table scoreboard_cells (
    contest_id   bigint  not null,
    user_id      bigint  not null,
    problem_id   bigint  not null,
    wrong_tries  integer not null,
    solved_at    timestamp(6) with time zone,
    primary key (contest_id, user_id, problem_id)
);
